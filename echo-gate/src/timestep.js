// Шаг логики по реальному времени кадра. Раньше шаг был фиксированным (1/60 с) с накопителем: при неровных кадрах
// на экране то 0, то 2 шага за кадр, и герой с камерой дрожали. Теперь каждый кадр двигает мир ровно на прошедшее
// время; слишком длинный кадр (вкладка была в фоне, просадка) режется на куски не длиннее MAX_STEP, чтобы логика
// не делала больших скачков.
export const MAX_STEP = 1 / 30;

/** Прогнать fn(шаг) на dt секунд, кусками не длиннее MAX_STEP. */
export function advance(dt, fn) {
  let left = dt;
  while (left > 1e-9) {
    const s = left > MAX_STEP ? MAX_STEP : left;
    fn(s);
    left -= s;
  }
}
